public Program()
{
    Runtime.UpdateFrequency = UpdateFrequency.Update10;
    Refresh();
    FleetLoad(false);   // send-only: the carrier broadcasts on the fleet channel too
}

void Refresh()
{
    GridTerminalSystem.GetBlocksOfType(_turrets, b => b.IsSameConstructAs(Me));
    GridTerminalSystem.GetBlocksOfType(_ctcs, b => b.IsSameConstructAs(Me));
}

public void Main(string arg, UpdateType src)
{
    if (!string.IsNullOrWhiteSpace(arg))
    {
        string a = arg.Trim();
        if (a.ToLowerInvariant().StartsWith("fleet ")) { FleetSendCmd(a.Substring(6).Trim()); Echo("Sent to the whole fleet: " + a.Substring(6).Trim()); }   // e.g. "fleet rtb"
        else
        {
            IGC.SendBroadcastMessage(Tag + "_CMD", a);
            if (a.ToLowerInvariant() == "reload") FleetLoad(false);
            Echo("Sent: " + arg);
        }
    }
    if ((src & UpdateType.Update10) == 0) return;
    if (++_tick % 60 == 0) Refresh();

    IGC.SendBroadcastMessage(Tag + "_HOME", Me.CubeGrid.WorldVolume.Center);
    FleetSendHome(Me.CubeGrid.WorldVolume.Center);
    IGC.SendBroadcastMessage(Tag + "_HOMER", Me.CubeGrid.WorldVolume.Radius);
    if (_flChan != "") IGC.SendBroadcastMessage(_flChan + "_HOMER", Me.CubeGrid.WorldVolume.Radius);

    int sent = 0;
    foreach (var t in _turrets)
        if (t.IsFunctional && t.HasTarget) { Send(t.GetTargetedEntity()); sent++; }
    foreach (var c in _ctcs)
        if (c.IsFunctional && c.HasTarget) { Send(c.GetTargetedEntity()); sent++; }
    Echo("Hornet link: " + sent + " target(s) shared\nDesignators: " + (_turrets.Count + _ctcs.Count));
}

void Send(MyDetectedEntityInfo e)
{
    if (e.IsEmpty() || e.Relationship != MyRelationsBetweenPlayerAndBlock.Enemies) return;
    var tup = new MyTuple<long, Vector3D, Vector3D, double, long>(
        e.EntityId, e.Position, new Vector3D(e.Velocity), e.BoundingBox.Size.Length() * 0.5, Me.EntityId);
    IGC.SendBroadcastMessage(Tag + "_TGT", tup);
    FleetSend(tup);
}
